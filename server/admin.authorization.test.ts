import { describe, expect, it } from "vitest";
import { appRouter } from "./routers";
import type { TrpcContext } from "./_core/context";

function contextFor(role: "user" | "admin"): TrpcContext {
  return {
    user: {
      id: 1,
      openId: "test-user",
      name: "Test User",
      email: "test@example.com",
      loginMethod: "manus",
      role,
      createdAt: new Date(),
      updatedAt: new Date(),
      lastSignedIn: new Date(),
    },
    req: { protocol: "https", headers: {} } as TrpcContext["req"],
    res: {} as TrpcContext["res"],
  };
}

describe("administrator router protection", () => {
  it("rejects an authenticated student before administrative data is accessed", async () => {
    const caller = appRouter.createCaller(contextFor("user"));

    await expect(caller.admin.exams()).rejects.toMatchObject({ code: "FORBIDDEN" });
  });
});
